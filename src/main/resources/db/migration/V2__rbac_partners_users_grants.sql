-- =====================================================================================================
-- identity-access-service · V2 · Permission-based RBAC + scoped grants (BRD §3, §4: ACC-1, 2, 6, 11)
--   permission ─< role_permission >─ role ─< role_grant >─ user_account >─ partner_org
--                                             ├─< grant_geo_scope  (region | country | territory)
--                                             └─< grant_bu_scope   (no rows = all business units)
-- =====================================================================================================

CREATE TABLE iam.permission (
    permission_code varchar(64)  PRIMARY KEY
        CHECK (permission_code ~ '^[a-z]+(-[a-z]+)*:[a-z]+(-[a-z]+)*$'),         -- e.g. case:transition
    description     varchar(200) NOT NULL
);

CREATE TABLE iam.role (
    role_code         varchar(40)  PRIMARY KEY CHECK (role_code ~ '^[A-Z][A-Z_]+$'),
    name              varchar(80)  NOT NULL,
    role_group        varchar(24)  NOT NULL
        CHECK (role_group IN ('GROWER', 'CHANNEL_PARTNER', 'FIELD_STAFF', 'CENTRAL', 'MANAGEMENT', 'GOVERNANCE')),
    -- Delegation (ACC-2): an admin may only grant roles with role_level <= their own highest admin role level.
    role_level        smallint     NOT NULL CHECK (role_level BETWEEN 0 AND 100),
    -- How far a grant of this role reaches over data; combined with the grant's geo/BU scope at runtime.
    scope_kind        varchar(16)  NOT NULL
        CHECK (scope_kind IN ('OWN', 'ORG', 'ASSIGNED', 'TERRITORY', 'COUNTRY', 'REGION', 'GLOBAL')),
    allowed_user_type varchar(16)  NOT NULL CHECK (allowed_user_type IN ('GROWER', 'PARTNER', 'STAFF')),
    pii_clearance     varchar(8)   NOT NULL CHECK (pii_clearance IN ('NONE', 'MASKED', 'FULL')),   -- ACC-3
    privileged        boolean      NOT NULL DEFAULT false   -- shown on the access-monitoring dashboard (ACC-9)
);

CREATE TABLE iam.role_permission (
    role_code       varchar(40) NOT NULL REFERENCES iam.role (role_code),
    permission_code varchar(64) NOT NULL REFERENCES iam.permission (permission_code),
    PRIMARY KEY (role_code, permission_code)
);
CREATE INDEX role_permission_perm_ix ON iam.role_permission (permission_code);

-- Segregation of duties (ACC-6): a user may not hold both roles at the same time. Stored once per pair.
CREATE TABLE iam.sod_conflict (
    role_code_a varchar(40)  NOT NULL REFERENCES iam.role (role_code),
    role_code_b varchar(40)  NOT NULL REFERENCES iam.role (role_code),
    reason      varchar(200) NOT NULL,
    PRIMARY KEY (role_code_a, role_code_b),
    CONSTRAINT sod_pair_ordered CHECK (role_code_a < role_code_b)
);

-- Channel partners (IAM-3, ACC-11). Distributors are top level; retailers may sit under a distributor.
CREATE TABLE iam.partner_org (
    partner_org_id        bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code          char(2)      NOT NULL REFERENCES iam.country (country_code),
    org_type              varchar(16)  NOT NULL CHECK (org_type IN ('DISTRIBUTOR', 'RETAILER')),
    parent_partner_org_id bigint       REFERENCES iam.partner_org (partner_org_id),
    legal_name            varchar(200) NOT NULL,
    tax_id                varchar(32)  NOT NULL,             -- GSTIN / CNPJ / EIN / VAT
    status                varchar(16)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED')),
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    version               integer      NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT partner_tax_id_uq UNIQUE (country_code, tax_id),
    CONSTRAINT partner_distributor_is_top_level CHECK (org_type = 'RETAILER' OR parent_partner_org_id IS NULL)
);
CREATE INDEX partner_org_parent_ix ON iam.partner_org (parent_partner_org_id);

-- Identity is proven by Keycloak; this table never stores passwords or OTP secrets.
-- Phone numbers are stored only as an HMAC-SHA256 (keyed, so not reversible by dictionary) + last 4 digits.
CREATE TABLE iam.user_account (
    user_id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_subject  uuid         NOT NULL UNIQUE,                     -- Keycloak "sub"
    user_type         varchar(16)  NOT NULL CHECK (user_type IN ('GROWER', 'PARTNER', 'STAFF')),
    home_country_code char(2)      NOT NULL REFERENCES iam.country (country_code),
    partner_org_id    bigint       REFERENCES iam.partner_org (partner_org_id),
    display_name      varchar(120) NOT NULL,
    email             varchar(254),
    phone_hmac        bytea        CHECK (octet_length(phone_hmac) = 32),
    phone_last4       char(4)      CHECK (phone_last4 ~ '^[0-9]{4}$'),
    status            varchar(16)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DEACTIVATED')),
    last_login_at     timestamptz,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    version           integer      NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT user_partner_matches_type CHECK ((user_type = 'PARTNER') = (partner_org_id IS NOT NULL)),
    CONSTRAINT user_phone_parts_together CHECK ((phone_hmac IS NULL) = (phone_last4 IS NULL))
);
CREATE UNIQUE INDEX user_account_phone_uq ON iam.user_account (phone_hmac) WHERE phone_hmac IS NOT NULL;
CREATE INDEX user_account_partner_ix ON iam.user_account (partner_org_id) WHERE partner_org_id IS NOT NULL;

-- A grant = role + scope + validity (ACC-1). Grants are never deleted: revocation is recorded (audit, ACC-10).
CREATE TABLE iam.role_grant (
    grant_id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint       NOT NULL REFERENCES iam.user_account (user_id),
    role_code           varchar(40)  NOT NULL REFERENCES iam.role (role_code),
    valid_from          timestamptz  NOT NULL DEFAULT now(),
    valid_to            timestamptz,
    granted_by_user_id  bigint       REFERENCES iam.user_account (user_id),   -- NULL only for bootstrap/system
    granted_at          timestamptz  NOT NULL DEFAULT now(),
    grant_reason        varchar(300) NOT NULL,
    revoked_at          timestamptz,
    revoked_by_user_id  bigint       REFERENCES iam.user_account (user_id),
    revoke_reason       varchar(300),
    version             integer      NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT grant_validity_order CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT grant_no_self_grant CHECK (granted_by_user_id IS DISTINCT FROM user_id),           -- ACC-6
    CONSTRAINT grant_revocation_complete CHECK (
        (revoked_at IS NULL AND revoked_by_user_id IS NULL AND revoke_reason IS NULL)
        OR (revoked_at IS NOT NULL AND revoked_by_user_id IS NOT NULL AND revoke_reason IS NOT NULL))
);
CREATE INDEX role_grant_active_user_ix ON iam.role_grant (user_id) WHERE revoked_at IS NULL;
CREATE INDEX role_grant_role_ix ON iam.role_grant (role_code) WHERE revoked_at IS NULL;
CREATE INDEX role_grant_expiry_ix ON iam.role_grant (valid_to) WHERE revoked_at IS NULL AND valid_to IS NOT NULL;

-- Geo scope: exactly one of region / country / territory per row, each with a real FK.
CREATE TABLE iam.grant_geo_scope (
    grant_geo_scope_id bigint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id           bigint     NOT NULL REFERENCES iam.role_grant (grant_id),
    region_code        varchar(8) REFERENCES iam.region (region_code),
    country_code       char(2)    REFERENCES iam.country (country_code),
    territory_id       bigint     REFERENCES iam.territory (territory_id),
    CONSTRAINT geo_scope_exactly_one CHECK (num_nonnulls(region_code, country_code, territory_id) = 1),
    CONSTRAINT geo_scope_uq UNIQUE NULLS NOT DISTINCT (grant_id, region_code, country_code, territory_id)
);
CREATE INDEX grant_geo_scope_grant_ix ON iam.grant_geo_scope (grant_id);

-- BU scope: rows restrict the grant to those BUs; no rows = all BUs.
CREATE TABLE iam.grant_bu_scope (
    grant_id bigint     NOT NULL REFERENCES iam.role_grant (grant_id),
    bu_code  varchar(8) NOT NULL REFERENCES iam.business_unit (bu_code),
    PRIMARY KEY (grant_id, bu_code)
);
